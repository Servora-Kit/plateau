// Command protoc-gen-plateau-audit translates Plateau Audit annotations into
// audit_rules.gen.go files consumed by Plateau Audit runtime.
package main

import (
	"fmt"
	"path"

	auditpb "github.com/Servora-Kit/plateau/api/gen/go/plateau/security/audit/v1"
	"github.com/Servora-Kit/plateau/internal/codegen/ruleplan"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		return generate(gen)
	})
}

func generate(gen *protogen.Plugin) error {
	groups, err := ruleplan.Build(gen, ruleplan.Config[*auditpb.AuditRule]{
		MethodExtension:  auditpb.E_Rule,
		ServiceExtension: auditpb.E_ServiceDefault,
		ValidateDeclared: func(context ruleplan.DeclarationContext, rule *auditpb.AuditRule) error {
			method := "<service_default>"
			if context.Method != nil {
				method = string(context.Method.Desc.Name())
			}
			return validateRule(
				context.File.Desc.Path(),
				string(context.Service.Desc.FullName()),
				method,
				rule,
			)
		},
	})
	if err != nil {
		return err
	}
	for _, group := range groups {
		file := group.TargetFile
		generated := gen.NewGeneratedFile(
			path.Join(group.Directory, "audit_rules.gen.go"),
			file.GoImportPath,
		)
		writeFile(generated, file.GoPackageName, group.Entries)
	}
	return nil
}

func validateRule(file, service, method string, rule *auditpb.AuditRule) error {
	if rule == nil {
		return nil
	}
	switch mode := rule.GetMode(); mode {
	case auditpb.AuditMode_AUDIT_MODE_UNSPECIFIED,
		auditpb.AuditMode_AUDIT_MODE_DISABLED,
		auditpb.AuditMode_AUDIT_MODE_ENABLED:
	default:
		return fmt.Errorf("%s: service %s method %s: unknown AuditMode %d", file, service, method, mode)
	}
	switch category := rule.GetCategory(); category {
	case auditpb.AuditCategory_AUDIT_CATEGORY_UNSPECIFIED,
		auditpb.AuditCategory_AUDIT_CATEGORY_AUTHN,
		auditpb.AuditCategory_AUDIT_CATEGORY_RESOURCE,
		auditpb.AuditCategory_AUDIT_CATEGORY_AUTHZ:
		return nil
	default:
		return fmt.Errorf("%s: service %s method %s: unknown AuditCategory %d", file, service, method, category)
	}
}

func writeFile(g *protogen.GeneratedFile, packageName protogen.GoPackageName, rules []ruleplan.Entry[*auditpb.AuditRule]) {
	auditPackage := protogen.GoImportPath("github.com/Servora-Kit/plateau/api/gen/go/plateau/security/audit/v1")
	protoPackage := protogen.GoImportPath("google.golang.org/protobuf/proto")

	g.P("// Code generated by protoc-gen-plateau-audit. DO NOT EDIT.")
	g.P()
	g.P("package ", packageName)
	g.P()

	ruleIdent := g.QualifiedGoIdent(protogen.GoIdent{GoName: "AuditRule", GoImportPath: auditPackage})
	protoClone := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Clone", GoImportPath: protoPackage})

	g.P("// _auditRules is the immutable backing store for AuditRules.")
	g.P("var _auditRules = map[string]*", ruleIdent, "{")
	for _, entry := range rules {
		rule := entry.Rule
		modeIdent := g.QualifiedGoIdent(protogen.GoIdent{
			GoName:       "AuditMode_" + rule.GetMode().String(),
			GoImportPath: auditPackage,
		})
		g.P(fmt.Sprintf("\t%q: {", entry.Operation))
		g.P("\t\tMode: ", modeIdent, ",")
		if rule.GetCategory() != auditpb.AuditCategory_AUDIT_CATEGORY_UNSPECIFIED {
			categoryIdent := g.QualifiedGoIdent(protogen.GoIdent{
				GoName:       "AuditCategory_" + rule.GetCategory().String(),
				GoImportPath: auditPackage,
			})
			g.P("\t\tCategory: ", categoryIdent, ",")
		}
		g.P("\t},")
	}
	g.P("}")
	g.P()

	g.P("// AuditRules returns the audit rules declared via Plateau Audit annotations.")
	g.P("// Each call returns a fresh map and cloned rule messages.")
	g.P("func AuditRules() map[string]*", ruleIdent, " {")
	g.P("\tm := make(map[string]*", ruleIdent, ", len(_auditRules))")
	g.P("\tfor k, v := range _auditRules {")
	g.P("\t\tm[k] = ", protoClone, "(v).(*", ruleIdent, ")")
	g.P("\t}")
	g.P("\treturn m")
	g.P("}")
}
